# Windows counterpart of ./install: link dotfiles into place with junctions
# (no admin needed) and write the few Windows-only shims. Re-runnable.
#
#   powershell -ExecutionPolicy Bypass -File windows\install.ps1
$ErrorActionPreference = 'Stop'
$dots = Split-Path $PSScriptRoot
$cfg  = "$HOME\.config"

# XDG_CONFIG_HOME makes nvim, git and lazygit read ~/.config like on Linux.
foreach ($kv in @{ XDG_CONFIG_HOME = $cfg; EDITOR = 'nvim'; VISUAL = 'nvim' }.GetEnumerator()) {
    [Environment]::SetEnvironmentVariable($kv.Key, $kv.Value, 'User')
    Set-Item "env:$($kv.Key)" $kv.Value
}

# User PATH: drop empty/missing/duplicate entries, add the tools winget doesn't
# link. Git's unix tools (less for delta, grep, ...) go last so Windows' own
# find/sort/ssh keep winning.
$programs = 'C:\Programs'
$want = @(
    (Get-Item "$programs\Emacs\bin", "$programs\Emacs\*\bin" -ErrorAction SilentlyContinue | Select-Object -Last 1).FullName
    "$programs\Alacritty"
    "$programs\4coder"
    "$programs\raddbg"
    "$programs\TaskSlinger"
    "$programs\NASM"
    "$HOME\.local\bin"
    "$programs\Git\usr\bin"
)
New-Item -ItemType Directory -Force "$HOME\.local\bin" | Out-Null
$envKey = Get-Item 'HKCU:\Environment'
$entries = @($envKey.GetValue('PATH', '', 'DoNotExpandEnvironmentNames') -split ';') + $want
$seen = @{}
$clean = foreach ($e in $entries) {
    if (-not $e) { continue }
    $key = [Environment]::ExpandEnvironmentVariables($e).TrimEnd('\').ToLower()
    if ($seen[$key] -or -not (Test-Path $key)) { continue }
    $seen[$key] = $true
    $e
}
Set-ItemProperty 'HKCU:\Environment' PATH ($clean -join ';') -Type ExpandString
# SetEnvironmentVariable broadcasts the change so new windows see the new PATH
[Environment]::SetEnvironmentVariable('EDITOR', 'nvim', 'User')
"user PATH: $($clean.Count) entries"

function Link($target, $source) {
    if (Test-Path $target) {
        $item = Get-Item $target -Force
        if ($item.LinkType -eq 'Junction' -and $item.Target -eq $source) { return }
        if ($item.LinkType) { $item.Delete() }
        else { Move-Item $target "$target.bak-$(Get-Date -Format yyyyMMddHHmmss)" }
    }
    New-Item -ItemType Directory -Force (Split-Path $target) | Out-Null
    New-Item -ItemType Junction -Path $target -Target $source | Out-Null
    "linked $target -> $source"
}

# stow packages from hosts/default that have a Windows build
Link "$cfg\nvim"             "$dots\nvim\.config\nvim"
Link "$cfg\git"              "$dots\git\.config\git"
Link "$cfg\lazygit"          "$dots\lazygit\.config\lazygit"
Link "$env:APPDATA\lazygit"  "$dots\lazygit\.config\lazygit"
Link "$env:APPDATA\neovide"  "$dots\neovide\.config\neovide"
# Emacs on Windows treats %APPDATA% as ~ and prefers ~/.emacs.d
Link "$env:APPDATA\.emacs.d" "$dots\emacs\.config\emacs"

# Alacritty: reuse the repo config, add the Windows shell and a readable size
$ala = "$env:APPDATA\alacritty"
New-Item -ItemType Directory -Force $ala | Out-Null
$pwsh = "$env:ProgramFiles\PowerShell\7\pwsh.exe"
$shell = if (Test-Path $pwsh) { $pwsh.Replace('\', '/') } else { 'powershell' }
@"
# Generated by dotfiles/windows/install.ps1
[general]
import = ["$($dots.Replace('\','/'))/alacritty/.config/alacritty/alacritty.toml"]

[terminal.shell]
program = "$shell"
args = ["-NoLogo"]

[font]
size = 11.0
"@ | Set-Content -Encoding ascii "$ala\alacritty.toml"

# ssh: Windows OpenSSH has no ControlMaster, so drop those lines
$ssh = "$HOME\.ssh"
New-Item -ItemType Directory -Force "$ssh\config.d" | Out-Null
if (-not (Test-Path "$ssh\config")) {
    Get-Content "$dots\ssh\.ssh\config" | Where-Object { $_ -notmatch '^\s*(ControlMaster|ControlPath|ControlPersist|# Reuse one connection)' } |
        Set-Content -Encoding ascii "$ssh\config"
    "wrote $ssh\config"
}

# git/local (gitignored): commit signing needs ~/.ssh/id_ed25519; off until it exists
$gitLocal = "$dots\git\.config\git\local"
if (-not (Test-Path $gitLocal) -and -not (Test-Path "$ssh\id_ed25519.pub")) {
    "# Per-machine (Windows). Remove once ~/.ssh/id_ed25519 exists.`n[commit]`n`tgpgSign = false`n[tag]`n`tgpgSign = false" |
        Set-Content -Encoding ascii $gitLocal
    "wrote $gitLocal (signing off: no ssh key yet)"
}

# PowerShell profiles (5.1 and 7) source windows/profile.ps1
$docs = [Environment]::GetFolderPath('MyDocuments')
foreach ($p in "$docs\WindowsPowerShell\Microsoft.PowerShell_profile.ps1", "$docs\PowerShell\Microsoft.PowerShell_profile.ps1") {
    $line = ". `"$PSScriptRoot\profile.ps1`""
    New-Item -ItemType Directory -Force (Split-Path $p) | Out-Null
    if (-not (Test-Path $p) -or -not (Select-String -Quiet -SimpleMatch $line $p)) {
        Add-Content -Encoding utf8 $p $line
        "profile: $p"
    }
}

# Fonts (per-user): Liberation Mono for alacritty/emacs/ghostty, plus the 4coder fonts
$fontDir = "$env:LOCALAPPDATA\Microsoft\Windows\Fonts"
$fontReg = 'HKCU:\Software\Microsoft\Windows NT\CurrentVersion\Fonts'
New-Item -ItemType Directory -Force $fontDir | Out-Null
if (-not (Test-Path $fontReg)) { New-Item $fontReg | Out-Null }
$fourcoder = "$HOME\src\4coder\build\fonts"
if (Test-Path $fourcoder) {
    Add-Type -AssemblyName System.Drawing
    foreach ($f in Get-ChildItem $fourcoder -Filter *.ttf) {
        $dst = Join-Path $fontDir $f.Name
        if (-not (Test-Path $dst)) { Copy-Item $f.FullName $dst }
        $pfc = New-Object System.Drawing.Text.PrivateFontCollection
        $pfc.AddFontFile($dst)
        $name = "$($pfc.Families[0].Name) [$($f.BaseName)] (TrueType)"
        if ((Get-ItemProperty $fontReg).$name) { continue }
        Set-ItemProperty $fontReg $name $dst
        "font: $($pfc.Families[0].Name)"
    }
}

if (Get-Command git -ErrorAction SilentlyContinue) { git -C $dots config core.autocrlf false }
"done. Restart your terminal to pick up the profile and env."
